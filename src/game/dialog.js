/**
 * Создаёт подсистему диалогов.
 *
 * @param {object} ctx контекст игры
 * @returns {object} система диалогов
 */
export function createDialog(ctx) {
  let openId = null;

  /** Портрет персонажа (рисуется один раз и переиспользуется). */
  const portraits = { barkeep: barkeepIcon(112), blacksmith: blacksmithIcon(112) };

  /**
   * Собрать список тем разговора: обычные темы плюс темы дел.
   *
   * @param {string} id идентификатор персонажа
   * @returns {Array<object>}
   */
  function buildTopics(id) {
    const s = SCRIPTS[id];
    const topics = s.topics.map((t) => ({ label: t.label, text: t.text, trade: !!t.trade }));
    const questTopics = ctx.systems.quests ? ctx.systems.quests.topicsFor(id) : [];
    for (const t of questTopics) {
      topics.push({ label: t.label, text: t.text, act: t.act });
    }
    return topics;
  }

  /**
   * Открыть диалог с персонажем.
   *
   * @param {string} id идентификатор сценария
   * @returns {boolean} удалось ли открыть
   */
  function open(id) {
    const s = SCRIPTS[id];
    if (!s) return false;
    openId = id;

    // игра встаёт на паузу: курсор свободен, игрок не слушает клавиши
    ctx.mode = 'dialog';
    ctx.player.acceptInput = false;
    ctx.player.keys.clear();
    if (document.pointerLockElement) document.exitPointerLock();

    const npc = ctx.npcs?.[id] || ctx.systems.locations?.npcs?.[id];
    if (npc) npc.talk(true);

    ctx.ui.openDialog({
      name: s.name,
      title: s.title,
      text: s.greet,
      portrait: portraits[id] || null,
      topics: buildTopics(id),
    });
    return true;
  }

  /** Закрыть диалог и вернуть управление. */
  function close() {
    if (!openId) return;
    const npc = ctx.npcs?.[openId] || ctx.systems.locations?.npcs?.[openId];
    if (npc) npc.talk(false);
    openId = null;
    ctx.ui.closeDialog();
    ctx.mode = 'play';
    ctx.player.acceptInput = true;
    ctx.player.keys.clear();
    ctx.player.requestLock();
  }

  // кнопки внутри окна
  ctx.ui.onDialogTopic = (topic) => {
    if (!openId) return;
    ctx.ui.setDialogText(topic.text);
    // тема «показать товар» открывает торговлю с этим же торговцем
    if (topic.trade) {
      const who = openId;
      close();
      if (ctx.systems.trade) ctx.systems.trade.open(who);
      return;
    }
    // тема сюжета: взять или сдать дело
    if (topic.act) {
      topic.act();
      // состояние изменилось — темы перерисовываем на месте:
      // взятое дело сразу становится «по делу», а следующее — «есть работа»
      ctx.ui.setDialogTopics(buildTopics(openId));
    }
  };
  ctx.ui.onDialogClose = () => close();

  return {
    open,
    close,
    /** Открыт ли сейчас диалог. */
    get isOpen() { return !!openId; },
    /** Имя текущего собеседника. */
    get who() { return openId ? SCRIPTS[openId].name : ''; },
  };
}
