/**
 * Расстояние от точки до отрезка.
 *
 * @param {number} px координата X точки
 * @param {number} pz координата Z точки
 * @param {number[]} a первая точка отрезка `[x, z]`
 * @param {number[]} b вторая точка отрезка `[x, z]`
 * @returns {number} расстояние
 */
export function distToSeg(px, pz, a, b) {
  const dx = b[0] - a[0], dz = b[1] - a[1];
  const l2 = dx * dx + dz * dz;
  let t = l2 ? ((px - a[0]) * dx + (pz - a[1]) * dz) / l2 : 0;
  t = Math.max(0, Math.min(1, t));
  return Math.hypot(px - (a[0] + dx * t), pz - (a[1] + dz * t));
}

/**
 * Расстояние от точки до ближайшей тропинки.
 *
 * @param {number} x координата X
 * @param {number} z координата Z
 * @returns {number} расстояние
 */
export function distToTrails(x, z) {
  let best = Infinity;
  for (const t of TRAILS) {
    for (let i = 0; i < t.pts.length - 1; i++) {
      const d = distToSeg(x, z, t.pts[i], t.pts[i + 1]);
      if (d < best) best = d;
    }
  }
  return best;
}

/**
 * Пересекает ли ломаная прямоугольник постройки.
 *
 * Прямоугольник задаётся центром, половинами габаритов и поворотом —
 * так же, как считаются коллайдеры в игре.
 *
 * @param {[number, number][]} pts ломаная дороги
 * @param {{x: number, z: number, hx: number, hz: number, ry: number}} box постройка
 * @param {number} [pad] запас, м
 * @returns {boolean} true, если дорога заходит внутрь
 */
export function pathHitsBox(pts, box, pad = 0) {
  const c = Math.cos(box.ry || 0), s = Math.sin(box.ry || 0);
  /** Точка в локальных осях постройки. */
  const toLocal = (x, z) => {
    const dx = x - box.x, dz = z - box.z;
    return [c * dx - s * dz, s * dx + c * dz];
  };
  const hx = box.hx + pad, hz = box.hz + pad;
  for (let i = 0; i < pts.length - 1; i++) {
    const a = pts[i], b = pts[i + 1];
    const ax = a[0], az = a[1], bx = b[0], bz = b[1];
    // отрезок в локальных осях
    const la = toLocal(ax, az), lb = toLocal(bx, bz);
    // пересечение с прямоугольником (алгоритм отсечения отрезка)
    let t0 = 0, t1 = 1;
    const dx = lb[0] - la[0], dz = lb[1] - la[1];
    const clip = (p, q) => {
      if (Math.abs(p) < 1e-9) return q >= 0;
      const r = q / p;
      if (p < 0) { if (r > t1) return false; if (r > t0) t0 = r; }
      else { if (r < t0) return false; if (r < t1) t1 = r; }
      return true;
    };
    if (!clip(-dx, la[0] + hx)) continue;
    if (!clip(dx, hx - la[0])) continue;
    if (!clip(-dz, la[1] + hz)) continue;
    if (!clip(dz, hz - la[1])) continue;
    return true;
  }
  return false;
}
