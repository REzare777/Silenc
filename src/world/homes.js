    for (const sx of [-1, 1]) {
      B.put('iron', 0.16, 0.06, 0.16, sx * 1.1, 0.9, -0.6, 1.1);
      B.put('bone', 0.07, 0.24, 0.07, sx * 1.1, 1.05, -0.6, 1.1);
      B.put('ember', 0.05, 0.1, 0.05, sx * 1.1, 1.2, -0.6, 1.1);
    }
    B.put('greenCloth', 1.6, 0.03, 1.4, 0.2, 0.02, 0.9, 1.1);
    spots.push([P(0, 1.6, D / 2 - 0.35), 'Помолиться у иконы']);
